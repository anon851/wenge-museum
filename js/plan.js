// 自由隔墙：四面围合的小展亭，open 指开口方向
function pavilion(x0, x1, z0, z1, open, h = LOW) {
  const w = [], g = 3.2, cx = (x0 + x1) / 2, cz = (z0 + z1) / 2;
  const side = (s, a, b) => {
    const seg = (p, q) => {
      if (s === 'n') w.push([p, z0, q, z0, h]); if (s === 's') w.push([p, z1, q, z1, h]);
      if (s === 'w') w.push([x0, p, x0, q, h]); if (s === 'e') w.push([x1, p, x1, q, h]);
    };
    if (open.includes(s)) { const m = (a + b) / 2; seg(a, m - g / 2); seg(m + g / 2, b); } else seg(a, b);
  };
  side('n', x0, x1); side('s', x0, x1); side('w', z0, z1); side('e', z0, z1);
  return w;
}

