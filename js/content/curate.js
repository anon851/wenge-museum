// 过滤一个旧图集的档案柜：去掉外国情报文书、凑数条目和同名重复
export function curateArchive(old, list) {
  const drop = [...(DROP_ARCH[old] || []), ...DROP_ARCH_ANY], seen = new Set();
  return list.filter(o => {
    if (DROP_SRC.test(o.src || '') || DROP_ARCH_SRC.test(o.src || '')) return false;
    const t = o.t || '';
    if (drop.some(s => s[0] === '=' ? t.replace(/\s*\|.*$/, '') === s.slice(1) : t.includes(s))) return false;
    const key = t.replace(/（[^）]*）$/, '').replace(/\s*\|.*$/, '').trim();
    if (seen.has(key)) return false;
    seen.add(key); return true;
  });
}

